#!/usr/bin/env python3
"""Deterministic repository-standards extractor for brownfield changes.

Scans the repository for declared configuration, test layout, source directories,
existing #sec-* anchors and language/runtime versions, then writes a timestamp-free
report that the change skill treats as implicit constraints. The output is stable
for the same tree, so --check can be used in CI.

Exit codes: 0 success or report current; 1 report stale (--check);
2 usage error; 3 unexpected internal error.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

__version__ = "3.1.0"

EXIT_OK = 0
EXIT_STALE = 1
EXIT_USAGE = 2
EXIT_INTERNAL = 3

TICK = chr(96)

CONFIG_NAMES = (
    "pyproject.toml",
    "setup.cfg",
    "tox.ini",
    ".flake8",
    "ruff.toml",
    "mypy.ini",
    "package.json",
    "tsconfig.json",
    ".editorconfig",
    "Makefile",
    "justfile",
)
CONFIG_PREFIXES = (".eslintrc", ".prettierrc")
PRUNED_DIRS = {
    "node_modules",
    "__pycache__",
    "venv",
    "env",
    "dist",
    "build",
    "target",
    "coverage",
    "htmlcov",
}
TEST_DIRS = ("tests/unit", "tests/e2e", "tests/acceptance")
TEST_FILE_SUFFIXES = ("_test.go", ".test.ts", ".test.tsx", ".spec.ts")
ANCHOR_RE = re.compile(r"#sec-[a-z0-9-]+")
MAX_LISTED_FILES = 50


def relative_posix(path, root):
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except (OSError, ValueError):
        return path.resolve().as_posix()


def read_text(path):
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def load_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def iter_repository_files(root):
    """Yield files under root, pruning VCS, dependency and cache directories."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(
            name for name in dirnames if not name.startswith(".") and name not in PRUNED_DIRS
        )
        for name in sorted(filenames):
            yield Path(dirpath) / name


def detect_config_files(root):
    found = set()
    for path in iter_repository_files(root):
        name = path.name
        if name in CONFIG_NAMES or any(name.startswith(prefix) for prefix in CONFIG_PREFIXES):
            found.add(relative_posix(path, root))
    return sorted(found)


def detect_test_layout(root):
    directories = [relative + "/" for relative in TEST_DIRS if (root / relative).is_dir()]
    files = []
    for path in iter_repository_files(root):
        if path.name.endswith(TEST_FILE_SUFFIXES):
            files.append(relative_posix(path, root))
    files = sorted(files)
    return directories, files


def detect_source_dirs(root):
    directories = []
    for entry in sorted(root.iterdir(), key=lambda path: path.name):
        if not entry.is_dir():
            continue
        name = entry.name
        if name.startswith(".") or name in (".venv", "node_modules", "__pycache__"):
            continue
        # tasks/ is generated by the change/task-decomposition skills; it is output,
        # not a source tree, and must not churn the report on every scaffold.
        if name == "tasks":
            continue
        directories.append(name + "/")
    return directories


def detect_anchors(root):
    specs = root / ".specs"
    if not specs.is_dir():
        return []
    collected = {}
    for path in sorted(specs.rglob("*.md")):
        if not path.is_file():
            continue
        # generated change context and in-flight change proposals are output, not
        # specification sources: including them would make --check churn (and a
        # proposal quotes the anchor it changes).
        if path.relative_to(specs).parts[0] in ("change-context", "changes"):
            continue
        text = read_text(path)
        relative = relative_posix(path, root)
        for anchor in set(ANCHOR_RE.findall(text)):
            collected.setdefault(anchor, []).append(relative)
    return [(anchor, sorted(files)) for anchor, files in sorted(collected.items())]


def detect_runtime(root, config_files):
    runtime = []
    if "pyproject.toml" in config_files:
        text = read_text(root / "pyproject.toml")
        match = re.search(r'(?m)^\s*requires-python\s*=\s*["\']([^"\']+)["\']', text)
        if match:
            runtime.append(("Python", match.group(1), "pyproject.toml requires-python"))
        else:
            match = re.search(r'(?m)^\s*python\s*=\s*["\']([^"\']+)["\']', text)
            if match:
                runtime.append(("Python", match.group(1), "pyproject.toml poetry python constraint"))
    labels = {"node": "Node.js", "npm": "npm"}
    for relative in config_files:
        if Path(relative).name != "package.json":
            continue
        data = load_json(root / relative)
        engines = data.get("engines") if isinstance(data, dict) else None
        if not isinstance(engines, dict):
            continue
        for key in sorted(engines):
            value = engines[key]
            if isinstance(value, str):
                entry = (labels.get(key, key), value, relative + " engines." + key)
                if entry not in runtime:
                    runtime.append(entry)
    return runtime


def _add_command(commands, command, reason):
    for existing, _ in commands:
        if existing == command:
            return
    commands.append((command, reason))


def detect_commands(root, config_files):
    commands = []

    def text_of(name):
        return read_text(root / name)

    def has_prefix(prefix):
        return any(Path(relative).name.startswith(prefix) for relative in config_files)

    if "pyproject.toml" in config_files:
        text = text_of("pyproject.toml")
        if re.search(r"(?m)^\[tool\.ruff", text):
            _add_command(commands, "python -m ruff check .", "pyproject.toml [tool.ruff]")
        if re.search(r"(?m)^\[tool\.mypy", text):
            _add_command(commands, "python -m mypy .", "pyproject.toml [tool.mypy]")
        if re.search(r"(?m)^\[tool\.pytest", text):
            _add_command(commands, "python -m pytest", "pyproject.toml [tool.pytest.*]")
        if re.search(r"(?m)^\[tool\.black", text):
            _add_command(commands, "python -m black --check .", "pyproject.toml [tool.black]")
    if "ruff.toml" in config_files:
        _add_command(commands, "python -m ruff check .", "ruff.toml")
    if "mypy.ini" in config_files:
        _add_command(commands, "python -m mypy .", "mypy.ini")
    if ".flake8" in config_files:
        _add_command(commands, "python -m flake8 .", ".flake8")
    if "setup.cfg" in config_files:
        text = text_of("setup.cfg")
        if re.search(r"(?m)^\[flake8\]", text):
            _add_command(commands, "python -m flake8 .", "setup.cfg [flake8]")
        if re.search(r"(?m)^\[mypy\]", text):
            _add_command(commands, "python -m mypy .", "setup.cfg [mypy]")
        if re.search(r"(?m)^\[tool:pytest\]", text):
            _add_command(commands, "python -m pytest", "setup.cfg [tool:pytest]")
    if "tox.ini" in config_files:
        _add_command(commands, "python -m tox", "tox.ini")
        if re.search(r"(?m)^\[pytest\]", text_of("tox.ini")):
            _add_command(commands, "python -m pytest", "tox.ini [pytest]")
    # package.json may live at the root or in a workspace package (for example agent-core/).
    # Every detected manifest is scanned, and commands are prefixed with the package directory.
    for relative in config_files:
        if Path(relative).name != "package.json":
            continue
        directory = Path(relative).parent
        data = load_json(root / relative)
        scripts = data.get("scripts") if isinstance(data, dict) else None
        if (root / directory / "pnpm-lock.yaml").is_file():
            package_manager = "pnpm"
        elif (root / directory / "yarn.lock").is_file():
            package_manager = "yarn"
        else:
            package_manager = "npm"
        prefix = "" if str(directory) in (".", "") else "cd " + directory.as_posix() + " && "
        has_typecheck = False
        if isinstance(scripts, dict):
            for name, suffix in (("test", " test"), ("lint", " run lint"), ("typecheck", " run typecheck")):
                if isinstance(scripts.get(name), str):
                    has_typecheck = has_typecheck or name == "typecheck"
                    _add_command(
                        commands, prefix + package_manager + suffix, relative + " scripts." + name
                    )
        if not has_typecheck and (root / directory / "tsconfig.json").is_file():
            _add_command(
                commands, prefix + "npx --no-install tsc --noEmit", relative + " + tsconfig.json"
            )
    if "package.json" in config_files:
        if has_prefix(".eslintrc"):
            _add_command(commands, "npx --no-install eslint .", ".eslintrc* declares ESLint")
        if has_prefix(".prettierrc"):
            _add_command(commands, "npx --no-install prettier --check .", ".prettierrc* declares Prettier")
    if "Makefile" in config_files and re.search(r"(?m)^test\s*:", text_of("Makefile")):
        _add_command(commands, "make test", "Makefile test target")
    if "justfile" in config_files and re.search(r"(?m)^test(?:\s+[^:\n]+)?:", text_of("justfile")):
        _add_command(commands, "just test", "justfile test recipe")
    return commands


def build_constraints(config_files, runtime, test_directories, test_files, anchors, commands):
    constraints = []
    for label, version, source in runtime:
        constraints.append(
            label
            + " "
            + version
            + " is declared by "
            + source
            + "; keep generated code and bundled helpers compatible with it."
        )
    if test_directories:
        listed = ", ".join(TICK + directory.rstrip("/") + TICK for directory in test_directories)
        constraints.append("Tests live under " + listed + "; run them from the repository root.")
    if test_files:
        constraints.append(
            "Existing test files use the detected naming convention (for example "
            + TICK
            + test_files[0]
            + TICK
            + "); follow it for new tests."
        )
    if anchors:
        constraints.append(
            "Reuse one of the "
            + str(len(anchors))
            + " existing #sec-* anchors reported in section 4; do not invent a new specification "
            "section inside a change."
        )
    if commands:
        constraints.append(
            "Only the commands listed in section 6 are evidenced by declared configuration; do not "
            "claim additional tooling conventions."
        )
    else:
        constraints.append(
            "No build, test or lint command is evidenced by declared configuration; agree the "
            "verification commands with the repository maintainers instead of guessing."
        )
    if config_files:
        constraints.append(
            "Configuration changed? Regenerate this report and rerun the change lint; a stale report "
            "invalidates the plan."
        )
    return constraints


def build_report(root):
    config_files = detect_config_files(root)
    test_directories, test_files = detect_test_layout(root)
    source_directories = detect_source_dirs(root)
    anchors = detect_anchors(root)
    runtime = detect_runtime(root, config_files)
    commands = detect_commands(root, config_files)
    unique_anchors = [anchor for anchor, _ in anchors]
    constraints = build_constraints(
        config_files, runtime, test_directories, test_files, unique_anchors, commands
    )

    lines = [
        "# Repository Standards Report",
        "",
        "> Generated by the change skill's standards_extract.py. Deterministic and timestamp-free:",
        "> rerun it after any configuration change and use --check in CI. Never hand-edit this file.",
        "> The generated change-context directory, in-flight change proposals and the generated",
        "> tasks/ directory are excluded from the scan so reruns are stable.",
        "",
        "## 1. Detected configuration files",
        "",
    ]
    if config_files:
        lines.extend("- " + TICK + relative + TICK for relative in config_files)
    else:
        lines.append("(none detected)")
    lines.extend(["", "## 2. Test layout", ""])
    if test_directories:
        lines.extend("- " + TICK + directory + TICK + " (directory)" for directory in test_directories)
    if test_files:
        listed = test_files[:MAX_LISTED_FILES]
        lines.extend("- " + TICK + relative + TICK for relative in listed)
        if len(test_files) > len(listed):
            lines.append("- (+" + str(len(test_files) - len(listed)) + " more test files)")
    if not test_directories and not test_files:
        lines.append("(none detected)")
    lines.extend(["", "## 3. Top-level source directories", ""])
    if source_directories:
        lines.extend("- " + TICK + directory + TICK for directory in source_directories)
    else:
        lines.append("(none detected)")
    lines.extend(["", "## 4. Existing specification anchors", ""])
    if anchors:
        for anchor, files in anchors:
            rendered_files = ", ".join(TICK + relative + TICK for relative in files)
            lines.append("- " + TICK + anchor + TICK + " (" + rendered_files + ")")
    else:
        lines.append("(none detected)")
    lines.extend(["", "## 5. Language and runtime", ""])
    if runtime:
        lines.extend(
            "- "
            + label
            + ": "
            + TICK
            + version
            + TICK
            + " ("
            + TICK
            + source
            + TICK
            + ")"
            for label, version, source in runtime
        )
    else:
        lines.append("(none detected)")
    lines.extend(["", "## 6. Commands implied by declared configuration", ""])
    if commands:
        lines.extend(
            "- " + TICK + command + TICK + " (" + reason + ")" for command, reason in commands
        )
    else:
        lines.append("(none detected)")
    lines.extend(["", "## 7. Implicit constraints", ""])
    lines.extend("- " + constraint for constraint in constraints)
    lines.append("")
    return "\n".join(lines), {
        "config_files": config_files,
        "test_layout": {"directories": test_directories, "files": test_files},
        "source_dirs": source_directories,
        "anchors": [{"anchor": anchor, "files": files} for anchor, files in anchors],
        "runtime": [
            {"name": label, "version": version, "source": source}
            for label, version, source in runtime
        ],
        "commands": [{"command": command, "reason": reason} for command, reason in commands],
        "implicit_constraints": constraints,
    }


def build_parser():
    parser = argparse.ArgumentParser(
        prog="standards_extract.py",
        description="Extract deterministic repository standards for brownfield change planning.",
        epilog=(
            "Exit codes: 0 success or report current, 1 report stale (--check), 2 usage error, "
            "3 unexpected error. Example: python standards_extract.py --repo-root . --check"
        ),
    )
    parser.add_argument("--repo-root", default=".", help="Repository root to scan (default: .).")
    parser.add_argument(
        "--out",
        default=None,
        help="Report path (default: <repo-root>/.specs/change-context/standards.md).",
    )
    parser.add_argument("--check", action="store_true", help="Exit 1 when the existing report is stale.")
    parser.add_argument("--dry-run", action="store_true", help="Print the target path; write nothing.")
    parser.add_argument("--json", action="store_true", help="Print a single machine-readable JSON object.")
    parser.add_argument("--version", action="version", version="%(prog)s " + __version__)
    return parser


def run(args):
    root = Path(args.repo_root).expanduser().resolve()
    if not root.is_dir():
        print("error: repository root is not a directory: " + str(root), file=sys.stderr)
        return EXIT_USAGE

    if args.out:
        out = Path(args.out).expanduser()
        if not out.is_absolute():
            out = (Path.cwd() / out).resolve()
        else:
            out = out.resolve()
    else:
        out = (root / ".specs" / "change-context" / "standards.md").resolve()

    try:
        report, summary = build_report(root)
    except OSError as exc:
        print("error: cannot scan the repository: " + str(exc), file=sys.stderr)
        return EXIT_INTERNAL
    summary["tool"] = "standards_extract"
    summary["out"] = str(out)

    if args.check:
        try:
            current = out.read_text(encoding="utf-8") if out.is_file() else None
        except OSError:
            current = None
        up_to_date = current == report
        payload = dict(summary)
        payload.update({"check": True, "up_to_date": up_to_date, "stale": not up_to_date})
        if args.json:
            print(json.dumps(payload, ensure_ascii=False))
        if up_to_date:
            if not args.json:
                print("standards report is current: " + str(out))
            return EXIT_OK
        print("standards report is stale: " + str(out), file=sys.stderr)
        return EXIT_STALE

    if args.dry_run:
        if args.json:
            payload = dict(summary)
            payload.update({"dry_run": True, "written": False})
            print(json.dumps(payload, ensure_ascii=False))
        else:
            print("[dry-run] would write " + str(out))
            print("[dry-run] no files written")
        return EXIT_OK

    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report, encoding="utf-8")
    except OSError as exc:
        print("error: cannot write the standards report: " + str(exc), file=sys.stderr)
        return EXIT_INTERNAL

    if args.json:
        payload = dict(summary)
        payload.update({"dry_run": False, "written": True})
        print(json.dumps(payload, ensure_ascii=False))
    else:
        print("wrote standards report: " + str(out))
        print(
            "configuration files: "
            + str(len(summary["config_files"]))
            + ", anchors: "
            + str(len(summary["anchors"]))
            + ", commands: "
            + str(len(summary["commands"]))
        )
    return EXIT_OK


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return run(args)
    except Exception as exc:  # noqa: BLE001 - last-resort safety net
        print("error: unexpected failure: " + str(exc), file=sys.stderr)
        return EXIT_INTERNAL


if __name__ == "__main__":
    sys.exit(main())
